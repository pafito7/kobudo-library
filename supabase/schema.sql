on conflict (name) do nothing;

create table if not exists public.folders (
  id uuid primary key default gen_random_uuid(),
  category text not null,
  name text not null check (char_length(name) between 1 and 80),
  created_by uuid default auth.uid() references auth.users (id),
  created_at timestamptz not null default now(),
  unique (category, name)
);

alter table public.folders drop constraint if exists folders_category_check;
alter table public.folders alter column created_by drop not null;

create table if not exists public.videos (
  id uuid primary key default gen_random_uuid(),
  category text not null,
  folder text,
  title text not null check (char_length(title) between 1 and 200),
  description text not null default '',
  url text not null default '',
  author_id uuid not null default auth.uid() references public.profiles (id),
  created_at timestamptz not null default now()
);

alter table public.videos drop constraint if exists videos_category_check;

do $$
begin
  if not exists (
    select 1 from pg_constraint
    where conname = 'folders_category_fkey'
      and conrelid = 'public.folders'::regclass
  ) then
    alter table public.folders
      add constraint folders_category_fkey
      foreign key (category) references public.categories (name) on update cascade;
  end if;
  if not exists (
    select 1 from pg_constraint
    where conname = 'videos_category_fkey'
      and conrelid = 'public.videos'::regclass
  ) then
    alter table public.videos
      add constraint videos_category_fkey
      foreign key (category) references public.categories (name) on update cascade;
  end if;
end;
$$;

create table if not exists public.comments (
  id uuid primary key default gen_random_uuid(),
  video_id uuid not null references public.videos (id) on delete cascade,
  author_id uuid not null default auth.uid() references public.profiles (id),
  body text not null check (char_length(body) between 1 and 5000),
  created_at timestamptz not null default now()
);

